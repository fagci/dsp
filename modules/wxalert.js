/* ============================ Оповещения NWS / CAP · ретрансляция в APRS ============================
   NWS Alerts — активные оповещения api.weather.gov (штат, зона или точка) или любой CAP/Atom-адрес, либо документ с входа doc
   (тест без сети). Фильтр по FIPS и кодам событий — тот же, что у SAME / EAS Decoder. Последний удачный ответ хранится и
   показывается с пометкой «stale». Разбор и сборка — wxalert-kernels.js (пары Parse ↔ Build, tools/test-wxalert.mjs).
   Alert → APRS — записи SAME или NWS → бюллетень «:BLN1WX   :…» и/или объект с координатами для Transmit AX.25/APRS.
   Alert Test Generator — зеркало разбора: собирает NWS-JSON или CAP из полей (для проверки без сети; не излучать в эфир). */

const WX_SAMPLE={src:'TEST',kind:'header',id:'test-1',event:'TOR',eventName:'Tornado Warning',locations:'040109',area:'Oklahoma, OK',severity:'Extreme',urgency:'Immediate',
  certainty:'Observed',headline:'TEST — Tornado Warning (not real)',description:'This is a test message generated by DSP.',instruction:'Do not act on this message.',sender:'TEST',lat:35.47,lon:-97.52};

/* ---------- NWS Alerts ---------- */
async function wxLoad(n,I){
  if(n.busy) return;
  n.busy=true; n.lastAt=performance.now();
  try{
    let recs, stale=0, msg='';
    const doc=typeof I.doc==='string' ? I.doc : '';
    if(doc){ recs=wxParseAny(doc); if(!recs) throw new Error('document is neither NWS JSON nor CAP XML'); }
    else {
      const [la,lo]=n.p.point ? ndCentre(n,I) : [null,null];
      const url=n.p.url.trim() || wxNwsUrl({area:n.p.area,lat:la,lon:lo});
      const r=await ndGet(n,'w',url,'text',{cache:'wx'+ndHash(url)});
      recs=wxParseAny(r.j); if(!recs) throw new Error('unexpected answer');
      stale=r.stale; msg=ndStatus(n,r); n.at=r.at;
    }
    n.all=recs.filter(r=>wxMatch(r,n.p.fips,n.p.events));
    n.stale=stale; n.msg=msg;
    let fresh=wxDiff(n.all,n.seen);
    if(n.first && !n.p.first) fresh=[];                       // активные на старте — не новые
    n.first=false;
    if(fresh.length){ n.pend.push(...fresh); }
    n.rev++;
  }catch(e){ const t=ndErr(e); if(t) n.msg='failed: '+t; n.rev++; }
  finally{ n.busy=false; }
}
def({ id:'wxAlerts', title:'NWS Alerts (CAP)', cat:'Sources', readout:true, tall:true, w:340,
  kw:'nws noaa weather alert warning watch tornado cap atom ipaws skywarn same fips oklahoma severe',
  ins:[{n:'doc',t:'txt'},{n:'lat',t:'num'},{n:'lon',t:'num'},{n:'update',t:'num'}],
  outs:[{n:'rec',t:'rec'},{n:'text',t:'txt'},{n:'new',t:'num'},{n:'count',t:'num'},{n:'all',t:'rec'},{n:'stale',t:'num'}],
  params:[{n:'area',t:'text',d:'OK',label:'state (OK) or forecast zone (OKZ025); empty — whole country'},
          {n:'point',t:'check',d:false,label:'by point instead (lat / lon wires, parameters or My Position)'},
          {n:'lat',t:'num',d:0,label:'latitude (0 and 0 — My Position or wires)'},
          {n:'lon',t:'num',d:0,label:'longitude'},
          {n:'url',t:'text',d:'',label:'own address (CAP XML / Atom / NWS JSON) instead of the above',adv:true},
          {n:'fips',t:'text',d:'',label:'only these areas: OK, 40109, 040109… (empty — all)'},
          {n:'events',t:'text',d:'',label:'only these events: TOR SVR *W, !RWT (empty — all)'},
          {n:'refresh',t:'range',min:1,max:30,step:1,d:2,label:'refresh, min'},
          {n:'auto',t:'check',d:true,label:'update by itself'},
          {n:'first',t:'check',d:true,label:'send the alerts that are active at start as new'},
          {n:'go',t:'button',label:'⟳ Update now',fn:n=>{ n.want=true; }},
          {n:'proxy',t:'check',d:false,label:'always through the CORS proxy from Settings'}],
  init:n=>{ n.all=[]; n.pend=[]; n.seen=new Set(); n.first=true; n.msg=''; n.busy=false; n.lastAt=-1e9; n.want=false; n.up=false; n.at=0; n.stale=0; n.rev=0; n.lastDoc=''; },
  dispose:n=>ndAbort(n),
  drawKey:n=>n.msg+'|'+n.rev+'|'+n.busy,
  process(n,I){
    const doc=typeof I.doc==='string' ? I.doc : '';
    if(doc && doc!==n.lastDoc){ n.lastDoc=doc; n.want=true; n.first=false; }
    if(ndPulse(n,'up',I.update)) n.want=true;
    if(!n.busy && (n.want || (n.p.auto && !doc && performance.now()-n.lastAt>n.p.refresh*60000))){ n.want=false; wxLoad(n,I); }
    const out=n.pend.splice(0);
    return {rec:out.length ? out : null, text:out.length ? out.map(r=>r.text).join('\n') : null, new:out.length ? 1 : 0, count:n.all.length, all:n.all, stale:n.stale|0};
  },
  draw(n){
    const L=['⚠ '+n.all.length+' active'+(n.busy ? ' · loading…' : '')];
    if(n.msg) L.push(n.msg);
    for(const r of n.all.slice(0,8)) L.push(r.event.padEnd(4)+r.text.slice(r.eventName.length).replace(/^ · /,'').slice(0,60));
    ndShow(n,L.join('\n'));
  }
});

