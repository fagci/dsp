def({ id:'wxAlertTx', title:'Alert Test Generator (CAP / NWS JSON)', cat:'Protocols', readout:true, w:320,
  kw:'cap nws alert test generator encoder tornado fake loopback',
  ins:[{n:'go',t:'num'}], outs:[{n:'doc',t:'txt'},{n:'rec',t:'rec'}],
  params:[{n:'format',t:'select',opts:['CAP XML','NWS JSON'],d:'CAP XML',label:'document format'},
          {n:'event',t:'text',d:'TOR',label:'event code (SAME, three letters)'},
          {n:'loc',t:'text',d:'040109',label:'areas PSSCCC separated by space'},
          {n:'area',t:'text',d:'Oklahoma, OK',label:'area description'},
          {n:'lat',t:'num',d:35.47,label:'centre latitude (0 and 0 — no polygon)'},
          {n:'lon',t:'num',d:-97.52,label:'centre longitude'},
          {n:'minutes',t:'range',min:5,max:240,step:5,d:30,label:'valid for, min'},
          {n:'cancel',t:'check',d:false,label:'cancellation (msgType Cancel)'},
          {n:'send',t:'button',label:'Make (test only)',fn:n=>{ n.want=true; }}],
  init:n=>{ n.want=false; n.prevGo=0; n.n=0; n.last=''; },
  process(n,I){
    const go=I.go||0; if(go>.5 && n.prevGo<=.5) n.want=true; n.prevGo=go;
    if(!n.want) return {doc:null,rec:null};
    n.want=false;
    const code=String(n.p.event).toUpperCase().replace(/[^A-Z0-9]/g,'').slice(0,3).padEnd(3,'X');
    const now=Date.now(), loc=String(n.p.loc).split(/[\s,;-]+/).filter(x=>/^\d{6}$/.test(x)).join(' ');
    const r={...WX_SAMPLE,id:'test-'+(++n.n)+'-'+now.toString(36),event:code,eventName:WX_EVENT_NAME[code]||code,locations:loc,states:wxStates(loc.split(' ')),area:n.p.area,
      sent:now,t:now,expires:now+n.p.minutes*60000,kind:n.p.cancel ? 'cancel' : 'header',lat:+n.p.lat||+n.p.lon ? +n.p.lat : null,lon:+n.p.lat||+n.p.lon ? +n.p.lon : null};
    r.text=r.eventName+' · '+r.area;
    const doc=n.p.format==='NWS JSON' ? JSON.stringify(wxBuildNws([r])) : wxBuildCap([r]);
    n.last=r.eventName+' · '+doc.length+' bytes · '+n.p.format;
    return {doc, rec:[r]};
  },
  draw(n){ ndShow(n,n.last||'press Make — a test alert (not for real alerting systems)'); }
});

/* ---------- Alert → APRS ---------- */
def({ id:'wxAprs', title:'Alert → APRS Message', cat:'Protocols', readout:true, w:320,
  kw:'aprs bulletin object relay alert same nws tornado weather bln',
  ins:[{n:'rec',t:'rec'}], outs:[{n:'text',t:'txt'},{n:'go',t:'num'},{n:'sent',t:'num'}],
  params:[{n:'mode',t:'select',opts:['bulletin','object (needs coordinates)','both'],d:'bulletin',label:'what to send'},
          {n:'bln',t:'text',d:'BLN1WX',label:'bulletin addressee (BLN + digit + group, up to 9)'},
          {n:'sym',t:'text',d:'\\!',label:'object symbol: table + code (\\! — Emergency)'},
          {n:'lat',t:'num',d:0,label:'position for alerts without coordinates (SAME)'},
          {n:'lon',t:'num',d:0,label:'longitude'},
          {n:'skip',t:'text',d:'!RWT !RMT !NPT !DMO',label:'events to skip (tests); empty — relay everything'},
          {n:'gap',t:'range',min:2,max:120,step:1,d:6,label:'pause between frames, s (the transmitter takes a frame at a time)'}],
  init:n=>{ n.qq=[]; n.cool=0; n.pulse=0; n.sentN=0; n.last=''; n.seenId=new Map(); },
  process(n,I){
    for(const r of recList(I.rec)){
      if(!r || (r.kind!=='header' && r.kind!=='cancel' && r.kind!=='eom') || !r.event) continue;
      if(!wxEventMatch(r.event,n.p.skip)) continue;
      const key=(r.id||'')+'|'+r.event+'|'+r.kind+'|'+(r.expires||r.t||0);
      if(n.seenId.has(key)) continue; n.seenId.set(key,1); if(n.seenId.size>200) n.seenId.delete(n.seenId.keys().next().value);
      const m=String(n.p.mode);
      if(m!=='object (needs coordinates)') n.qq.push(wxAprsBulletin(r,{id:n.p.bln}));
      if(m!=='bulletin'){ const o=wxAprsObject(r,{sym:n.p.sym,lat:+n.p.lat,lon:+n.p.lon}); if(o) n.qq.push(o); else if(m!=='both') n.qq.push(wxAprsBulletin(r,{id:n.p.bln})); }
    }
    let text=null, go=0;
    if(n.pulse>0){ n.pulse--; }
    else if(n.qq.length && performance.now()>=n.cool){
      text=n.qq.shift(); n.cool=performance.now()+n.p.gap*1000; n.pulse=2; go=1; n.sentN++; n.last=text;
    }
    return {text, go, sent:n.sentN};
  },
  draw(n){ ndShow(n,n.sentN+' frame(s) queued for the transmitter'+(n.qq.length ? ' · '+n.qq.length+' waiting' : '')+(n.last ? '\n'+n.last : '\nwire rec from SAME / EAS Decoder or NWS Alerts; text and go → Transmit AX.25/APRS')); }
});
