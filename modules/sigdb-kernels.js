const SDB_FEATS=[['bw',2],['baud',3],['dev',4]];
// 1, если в диапазоне; за пределами — гауссов спад по расстоянию в октавах (0.5 окт. → 0.37)
function sdbRange(x,r){
  if(x>=r[0] && x<=r[1]) return 1;
  const d=Math.log2(x/(x<r[0] ? r[0] : r[1]));
  return Math.exp(-(d/0.5)*(d/0.5));
}
// m: {bw, dev, baud, freq} в Гц / Bd; нулевые и нечисловые пропускаются. Возвращает [{n, mod, score, note}], лучшие первыми
function sdbMatch(m,top){
  const have=SDB_FEATS.filter(([k])=>m[k]>0), fq=m.freq>0 ? m.freq/1e6 : 0;
  if(!have.length && !fq) return [];
  const out=[];
  for(const e of SDB){
    let s=1;
    for(const [k,i] of have) s*=e[i] ? sdbRange(m[k],e[i]) : 0.85;
    if(fq && e[5]){ let hit=false; for(const r of e[5]) if(fq>=r[0] && fq<=r[1]){ hit=true; break; } if(!hit) s*=0.2; }
    out.push({n:e[0], mod:e[1], score:s, note:e[6]});
  }
  out.sort((a,b)=>b.score-a.score);
  return out.slice(0,top||5);
}

IQK.sigDb={
  init(n){ n.ui=null; },
  process(n,I){
    const m={bw:pv(n,I,'bw'), dev:pv(n,I,'dev'), baud:pv(n,I,'baud'), freq:pv(n,I,'freq')};
    const r=sdbMatch(m,+n.p.top), min=+n.p.min/100;
    n.ui={r:r.filter(x=>x.score>=min), m};
    const b=n.ui.r[0];
    return {name:b ? b.n : '', mod:b ? b.mod : '', score:b ? b.score : 0,
      text:n.ui.r.map(x=>(x.score*100).toFixed(0)+'% '+x.n+' ('+x.mod+') — '+x.note).join('\n')};
  }};
