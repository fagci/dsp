// Запасные источники тайлов карты: node tools/test-geotiles.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.join(path.dirname(fileURLToPath(import.meta.url)),'..');
let bad=0; const ok=(n,c,x='')=>{ if(!c){ bad++; console.log('FAIL',n,x); } else console.log('ok  ',n); };
const ctx=vm.createContext({}); 
vm.runInContext(fs.readFileSync(path.join(root,'modules/geotiles-kernels.js'),'utf8')+';this.K={geoTileMark,geoTileDown,geoTileChoose,geoTileNote,GEO_TILE_FB};',ctx);
const K=ctx.K, have=['OSM','OpenTopoMap','OSM Humanitarian','CyclOSM','CARTO Dark','CARTO Light','Esri Satellite','Esri Topo','Esri Streets'];
const st={}, T0=1e6;
ok('healthy source is used as is',K.geoTileChoose('OSM',have,st,T0).name==='OSM' && K.geoTileChoose('OSM',have,st,T0).from===null);
for(let i=0;i<3;i++) K.geoTileMark(st,'OSM',false,403,T0+i);
ok('3 failures in a row — still not down',!K.geoTileDown(st,'OSM',T0+10));
K.geoTileMark(st,'OSM',false,403,T0+3);
const c=K.geoTileChoose('OSM',have,st,T0+10);
ok('4 failures in a row → spare map, with the status',c.name==='OSM Humanitarian' && c.from==='OSM' && c.code===403,JSON.stringify(c));
ok('note text',K.geoTileNote('OSM','CARTO Light',403)==='tiles: OSM HTTP 403 → CARTO Light' && K.geoTileNote('OSM','X',0)==='tiles: OSM unreachable → X');
K.geoTileMark(st,'OSM Humanitarian',false,429,T0+20); for(let i=0;i<3;i++) K.geoTileMark(st,'OSM Humanitarian',false,429,T0+21+i);
ok('spare is down too → next one',K.geoTileChoose('OSM',have,st,T0+30).name==='CARTO Light');
ok('after 5 minutes the source is tried again',K.geoTileChoose('OSM',have,st,T0+400000).from===null);
K.geoTileMark(st,'OSM',true,0,T0+400001);
ok('one success clears the failure run',!K.geoTileDown(st,'OSM',T0+400002) && st.OSM.run===0 && st.OSM.ok===1);
const st2={}; for(let i=0;i<4;i++) K.geoTileMark(st2,'Esri Satellite',false,403,T0);
ok('satellite has no street-map substitute → stays',K.geoTileChoose('Esri Satellite',have,st2,T0+1).from===null);
const st3={}; for(const n of ['OSM','OSM Humanitarian','CARTO Light','OpenTopoMap']) for(let i=0;i<4;i++) K.geoTileMark(st3,n,false,0,T0);
ok('everything down → the chosen one stays',K.geoTileChoose('OSM',have,st3,T0+1).name==='OSM');
ok('only names that exist are offered',K.geoTileChoose('OSM',['OSM'],st,T0+10).name==='OSM');
ok('every fallback is a known map',Object.entries(K.GEO_TILE_FB).every(([k,v])=>have.includes(k) && v.every(x=>have.includes(x) && x!==k)));
console.log(bad?bad+' FAILED':'all ok'); process.exit(bad?1:0);
