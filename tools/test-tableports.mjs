// Порты полей Table (p.pout, p.pref): node tools/test-tableports.mjs
import vm from 'node:vm';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.join(path.dirname(fileURLToPath(import.meta.url)),'..');
const src=fs.readFileSync(path.join(root,'modules/table.js'),'utf8');
const a=src.indexOf('// порты полей:'), b=src.indexOf('// фильтр, столбцы времени');
const ctx=vm.createContext({TBL_FIXED:new Set(['rec','row']),tcDef:(n,c)=>n.schema.types[c]||{},tcLinks:v=>String(v??'').split('|').map(s=>s.trim()).filter(Boolean),Undo:{push(){}},tblRebuild(){},console});
vm.runInContext(src.slice(a,b)+';this.K={tblPorts,tblOutSet,tblRefSet,tblRefVal};',ctx);
const K=ctx.K;
let bad=0; const ok=(n,c)=>{ if(!c){ bad++; console.log('FAIL',n); } else console.log('ok  ',n); };
const ports=n=>n.cols.map(c=>c.port).join();
const n={p:{cols:['name','freq','Owner','row']},schema:{types:{Owner:{t:'link',to:'People'}}},cl:[],all:[],rows:[],idx:0};
K.tblPorts(n);
ok('legacy patch: every column is a port',ports(n)==='name,freq,Owner,row_');
K.tblOutSet(n,'freq',false);
ok('unchecking materialises the rest',JSON.stringify(n.p.pout)==='["name","Owner","row"]' && ports(n)==='name,Owner,row_');
K.tblOutSet(n,'freq',true);
ok('checking puts it back in column order',ports(n)==='name,freq,Owner,row_');
K.tblRefSet(n,'Owner','phone',true);
n.refIdx=new Map([['People',new Map([['Ann',{phone:'123',name:'Ann'}]])]]);
ok('linked field is a port Link.Field',ports(n)==='name,freq,Owner,row_,Owner.phone');
n.cur={Owner:'Ann|Bob'};
ok('value comes from the first linked record',K.tblRefVal(n,n.cols.at(-1))==='123');
n.cur={Owner:'Zed'};
ok('unknown link gives empty',K.tblRefVal(n,n.cols.at(-1))==='');
K.tblRefSet(n,'Owner','phone',false);
ok('unchecking removes it',ports(n)==='name,freq,Owner,row_' && !('Owner' in n.p.pref));
console.log(bad ? bad+' FAILED' : 'all ok'); process.exit(bad?1:0);
