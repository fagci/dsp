// help/modules.md — справочник модулей из самих определений (порты, параметры, текст из README). В приложении тот же список строится на лету.
// node tools/gen-modref.mjs   (нужны Playwright и Chromium; страница отдаётся с локального http-сервера)
import {createRequire} from 'node:module';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.join(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(import.meta.url);
const {chromium}=require('playwright');
const types={'.html':'text/html','.js':'text/javascript','.css':'text/css','.json':'application/json','.md':'text/plain','.svg':'image/svg+xml','.png':'image/png','.wasm':'application/wasm'};
const srv=http.createServer((q,r)=>{
  const p=path.join(root,decodeURIComponent(q.url.split('?')[0]).replace(/\/$/,'/index.html'));
  fs.readFile(p,(e,b)=>{ if(e || !p.startsWith(root)){ r.writeHead(404); r.end(); return; }
    r.writeHead(200,{'content-type':types[path.extname(p)]||'application/octet-stream','cross-origin-opener-policy':'same-origin','cross-origin-embedder-policy':'require-corp'}); r.end(b); });
});
await new Promise(r=>srv.listen(0,r));
const b=await chromium.launch(); const pg=await b.newPage();
await pg.goto('http://localhost:'+srv.address().port+'/');
await pg.waitForFunction(()=>typeof MOD!=='undefined' && typeof PRESETS!=='undefined' && typeof hlpModCard==='function',null,{timeout:90000});
await pg.waitForTimeout(1500);
const data=await pg.evaluate(()=>{
  const src={}; for(const k in PRESETS) src[k]=String(PRESETS[k]);
  const use=hlpUsage(src);
  return Object.values(MOD).map(m=>({...hlpModCard(m),roleName:typeof modRole==='function' ? modRole(m) : '',presets:(use.get(m.id)||[]).length}));
});
const readme=fs.readFileSync(path.join(root,'README.md'),'utf8');
const bullets=await pg.evaluate(t=>{ const m=hlpBullets(t); return Object.fromEntries([...m].map(([k,v])=>[k,v[0]])); },readme);
await b.close(); srv.close();

const norm=s=>String(s).toLowerCase().replace(/[^\p{L}\p{N}]+/gu,' ').trim();
const clip=(s,n)=>s.length>n ? s.slice(0,n).replace(/\s+\S*$/,'')+' …' : s;
const pins=l=>l.map(p=>'`'+p.n+'`'+(p.t ? ' ('+p.t+')' : '')).join(', ');
const by=new Map();
for(const m of data){ if(!by.has(m.cat)) by.set(m.cat,[]); by.get(m.cat).push(m); }
let out='# Module reference\n\nGenerated by `node tools/gen-modref.mjs` from the module definitions — do not edit by hand. In the app the same list is built live (help → Module reference).\n\n';
out+=data.length+' modules. Pin types: see [Wires and port types](wires.md). The manual text is the first paragraph from the [README](../README.md).\n\n';
for(const [cat,list] of [...by].sort((a,b)=>String(a[0]).localeCompare(String(b[0])))){
  out+='## '+(cat||'Other')+'\n\n';
  for(const m of list.sort((a,b)=>a.title.localeCompare(b.title))){
    out+='### '+m.title+'\n\n`'+m.id+'`'+(m.presets ? ' · used in '+m.presets+' preset'+(m.presets>1 ? 's' : '') : '')+'\n\n';
    const t=bullets[norm(m.title)];
    if(t){ const x=t.replace(/^\*\*[^*]+\*\*\s*(\([^)]*\))?:?\s*/,'').split('\n')[0].replace(/!?\[([^\]]*)\]\((?!https?:)[^)]*\)/g,'$1').replace(/^./,c=>c.toUpperCase());   // относительные ссылки README здесь не работают
      out+=clip(x,420)+'\n\n'; }
    if(m.ins.length) out+='- **In:** '+pins(m.ins)+'\n';
    if(m.outs.length) out+='- **Out:** '+pins(m.outs)+'\n';
    const ps=m.params.filter(p=>!p.adv);
    if(ps.length) out+='- **Parameters:** '+ps.map(p=>'`'+p.n+'`'+(p.label && p.label!==p.n ? ' — '+p.label : '')).join('; ')+'\n';
    if(m.dynamic) out+='- The pins depend on the module settings.\n';
    out+='\n';
  }
}
fs.writeFileSync(path.join(root,'help/modules.md'),out);
console.log('help/modules.md: '+data.length+' modules, '+(out.length>>10)+' KB');
