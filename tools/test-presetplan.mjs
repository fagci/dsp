// План пересборки пресетов: node tools/test-presetplan.mjs
import fs from 'fs'; import vm from 'vm';
const ctx={}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../modules/presetplan-kernels.js',import.meta.url),'utf8')+';this.patchMigrate=patchMigrate;this.patchNames=patchNames;this.presetSrcIds=presetSrcIds;this.favToggle=favToggle;this.favClean=favClean;',ctx);
const {patchMigrate,patchNames,presetSrcIds,favToggle,favClean}=ctx;
let bad=0; const ok=(c,m)=>{ if(!c){ console.error('FAIL',m); bad++; } };
const B={A:1,B:1};
let m=patchMigrate({A:{x:1},B:{x:2},'Mine':{x:3},'Studio: DAW old':{x:4},'temp:1':{x:5}},B,['Studio: DAW']);
ok(Object.keys(m.user).join()==='Mine,temp:1' && m.dropped===3,'миграция: копии встроенных и снятые уходят, свои остаются');
ok(patchMigrate(null,B,[]).dropped===0 && Object.keys(patchMigrate({},new Set(['A']),null).user).length===0,'миграция: пустое хранилище');
ok(Object.keys(patchMigrate({A:1,Z:2},new Set(['A'])).user).join()==='Z','миграция: Set имён');
ok(patchMigrate({__proto__:null,toString:1},B).user.toString===1,'миграция: имя из Object.prototype — не встроенное');
ok(patchNames(B,{Mine:1,A:2}).join()==='A,B,Mine','список: перекрывающий патч не дублируется');
ok(patchNames(null,null).length===0,'список: пусто');
const ids=presetSrcIds("addNode('bleUart',1,2); addNode(\"sa\"); x='nfc_y'; `hid`",{bleUart:1,hid:1,nfc:1});
ok([...ids].sort().join()==='bleUart,hid','слова в кавычках: только известные id, целиком');
ok(favToggle([],'A').join()==='A' && favToggle(['A'],'B').join()==='B,A','star: a new one goes first');
ok(favToggle(['B','A'],'B').join()==='A' && favToggle(['A'],'A').length===0,'star: pressing again takes it off');
ok(favToggle(['A','A','',5,'B'],'C').join()==='C,A,A,B','star: junk entries are dropped (duplicates are left to favClean)');
ok(favToggle(['1','2','3'],'4',3).join()==='4,1,2','star: at most max');
ok(favToggle(null,'A').join()==='A' && favToggle(undefined,'A',0).join()==='A','star: no list is fine');
ok(favClean(['A','B','A','C',7,''],n=>n!=='B').join()==='A,C','favClean: dropped patches and duplicates go');
ok(favClean(null,()=>true).length===0,'favClean: no list');
if(bad) process.exit(1); console.log('presetplan ok');
