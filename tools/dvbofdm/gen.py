#!/usr/bin/env python3
"""Pulls the DVB-T2 tables and carrier maps out of GNU Radio gr-dtv (GPL-3.0-or-later) into plain C++ headers:
   gen.py <gnuradio checkout> <output dir>. Nothing of GNU Radio's runtime is used: only constants and the code that builds them."""
import os, re, shutil, sys

gr, out = sys.argv[1], sys.argv[2]
D = os.path.join(gr, 'gr-dtv')
os.makedirs(os.path.join(out, 'gnuradio', 'dtv'), exist_ok=True)
for f in ('dvbt2_config.h', 'dvb_config.h', 'dvbt_config.h', 'dvbs2_config.h'):
    shutil.copy(os.path.join(D, 'include/gnuradio/dtv', f), os.path.join(out, 'gnuradio/dtv', f))
shutil.copy(os.path.join(D, 'lib/dvb/dvb_defines.h'), os.path.join(out, 'dvb_defines.h'))
rd = lambda p: open(os.path.join(D, p), encoding='utf-8').read()

HDR = '// Generated by tools/dvbofdm/gen.py from GNU Radio gr-dtv (GPL-3.0-or-later, Copyright Free Software Foundation, Inc.)\n#pragma once\n'

# ---------------- carrier maps and pilots (dvbt2_pilotgenerator_cc) ----------------
h = rd('lib/dvbt2/dvbt2_pilotgenerator_cc_impl.h')
c = rd('lib/dvbt2/dvbt2_pilotgenerator_cc_impl.cc')
N = 'dvbt2_pilotgenerator_cc_impl'
pre = h[h.index('#define CHIPS'):h.index('namespace gr {')]
members = h[h.index('private:') + 8:h.index('public:')]
members = re.sub(r'\n\s*fft::fft_complex_rev ofdm_fft;', '', members)
params = h[h.index(N + '(', h.index('public:')) + len(N) + 1:]
params = params[:params.index(');')]
ctor_start = c.index(N + '::' + N + '(')
ctor_body = c[c.index('{', c.index('vlength)', ctor_start) if False else c.index('ofdm_fft_size(vlength)', ctor_start)) + 1:c.index('    set_output_multiple(num_symbols);')]
fns = c[c.index('void ' + N + '::init_prbs'):c.index('const gr_complex zero')]
tabs = c[c.index('const unsigned char ' + N + '::pn_sequence_table'):c.index('} /* namespace dtv */')]
res = HDR + '''#include <cmath>
#include <complex>
#include <cstdint>
#include <cstring>
#include <vector>
#include "gnuradio/dtv/dvb_config.h"
#include "gnuradio/dtv/dvbt2_config.h"
#include "dvb_defines.h"
#define GR_M_PI 3.14159265358979323846
typedef std::complex<float> gr_complex;
''' + pre + '''
namespace gr {
namespace dtv {
struct T2Struct {
''' + members + '''
    T2Struct(''' + params + ''');
};
T2Struct::T2Struct(''' + params + ''')
    : fft_size(fftsize), pilot_pattern(pilotpattern), carrier_mode(carriermode), papr_mode(paprmode),
      equalization_enable(equalization), ofdm_fft_size(vlength)
{''' + ctor_body + '''}
''' + fns + tabs + '''
} // namespace dtv
} // namespace gr
'''
res = res.replace(N, 'T2Struct')
open(os.path.join(out, 't2struct_gen.h'), 'w').write(res)
print('t2struct_gen.h', len(res))

# ---------------- P1 preamble tables (dvbt2_p1insertion_cc) ----------------
p1 = rd('lib/dvbt2/dvbt2_p1insertion_cc_impl.cc')
t = p1[p1.index('const int dvbt2_p1insertion_cc_impl::p1_active_carriers'):p1.index('} /* namespace dtv */')]
t = t.replace('const int dvbt2_p1insertion_cc_impl::p1_active_carriers[384]', 'static const int P1_ACTIVE[384]')
t = t.replace('const unsigned char dvbt2_p1insertion_cc_impl::s1_modulation_patterns[8][8]', 'static const unsigned char P1_S1[8][8]')
t = t.replace('const unsigned char dvbt2_p1insertion_cc_impl::s2_modulation_patterns[16][32]', 'static const unsigned char P1_S2[16][32]')
open(os.path.join(out, 'p1_gen.h'), 'w').write(HDR + t)
print('p1_gen.h', len(t))

# ---------------- LDPC tables (dvb_ldpc_bb): the ones DVB-T2 uses ----------------
ld = rd('lib/dvb/dvb_ldpc_bb_impl.cc')
want = ['1_2N', '3_5N', '2_3N_DVBT2', '3_4N', '4_5N', '5_6N', '1_4S', '1_2S', '3_5S_DVBT2', '2_3S', '3_4S', '4_5S', '5_6S']
body = HDR + '#include <cstdint>\n'
for nm in want:
    m = re.search(r'const uint16_t dvb_ldpc_bb_impl::ldpc_tab_' + nm + r'\[(\d+)\]\[(\d+)\] = \{(.*?)\n\};', ld, re.S)
    if not m:
        print('missing ldpc table', nm); continue
    body += 'static const uint16_t LDPC_T2_%s[%s][%s] = {%s\n};\n' % (nm, m.group(1), m.group(2), m.group(3))
open(os.path.join(out, 'ldpc_gen.h'), 'w').write(body)
print('ldpc_gen.h', len(body))

# ---------------- L1 tables (dvbt2_framemapper_cc) ----------------
fm = rd('lib/dvbt2/dvbt2_framemapper_cc_impl.cc')
t = ''
for nm, typ in (('pre_puncture', 'int'), ('post_padding_bqpsk', 'int'), ('post_padding_16qam', 'int'), ('post_padding_64qam', 'int'),
                ('post_puncture_bqpsk', 'int'), ('post_puncture_16qam', 'int'), ('post_puncture_64qam', 'int'), ('mux16', 'int'), ('mux64', 'int')):
    m = re.search(r'const int dvbt2_framemapper_cc_impl::' + nm + r'\[(\d+)\] = \{(.*?)\};', fm, re.S)
    t += 'static const int L1_%s[%s] = {%s};\n' % (nm, m.group(1), m.group(2))
open(os.path.join(out, 'l1_gen.h'), 'w').write(HDR + t)
print('l1_gen.h', len(t))

# ---------------- frequency interleaver permutations (dvbt2_freqinterleaver_cc) ----------------
fh = rd('lib/dvbt2/dvbt2_freqinterleaver_cc_impl.h')
fc = rd('lib/dvbt2/dvbt2_freqinterleaver_cc_impl.cc')
N = 'dvbt2_freqinterleaver_cc_impl'
members = fh[fh.index('private:') + 8:fh.index('public:')]
params = fh[fh.index(N + '(', fh.index('public:')) + len(N) + 1:]
params = params[:params.index(');')]
cs = fc.index(N + '::' + N + '(')
body = fc[fc.index('{', fc.index('gr::io_signature::make(1, 1, sizeof(gr_complex))) {'.replace(') {', ')'), cs) if False else fc.index('sizeof(gr_complex)))', fc.index('gr::io_signature::make(1, 1, sizeof(gr_complex)),', cs) + 60)):fc.index('    if (N_FC == 0) {\n        set_output_multiple')]
body = body[body.index('{') + 1:]
body += '    if (N_FC == 0) {\n        interleaved_items = (N_P2 * C_P2) + (numdatasyms * C_DATA);\n    }\n'
tabs = fc[fc.index('const int ' + N + '::bitperm1keven'):fc.index('} /* namespace dtv */')]
res = HDR + '''#include <cstdint>
#include "gnuradio/dtv/dvb_config.h"
#include "gnuradio/dtv/dvbt2_config.h"
#include "dvb_defines.h"
namespace gr { namespace dtv {
struct T2FreqIl {
''' + members + '''
    T2FreqIl(''' + params + ''');
};
T2FreqIl::T2FreqIl(''' + params + ''')
{''' + body + '''}
''' + tabs + '''
} }
'''
res = res.replace(N, 'T2FreqIl')
open(os.path.join(out, 't2freq_gen.h'), 'w').write(res)
print('t2freq_gen.h', len(res))

# ---------------- bit interleaver (dvbt2_interleaver_bb): parity interleave, column twist, demux tables ----------------
bh = rd('lib/dvbt2/dvbt2_interleaver_bb_impl.h')
bc = rd('lib/dvbt2/dvbt2_interleaver_bb_impl.cc')
N = 'dvbt2_interleaver_bb_impl'
members = bh[bh.index('private:') + 8:bh.index('public:')]
params = bh[bh.index(N + '(', bh.index('public:')) + len(N) + 1:]
params = params[:params.index(');')]
cs = bc.index(N + '::' + N + '(')
cb = bc[bc.index('{', bc.index('gr::io_signature::make(1, 1, sizeof(unsigned char)))', cs)):bc.index('inline void ' + N + '::interleave_parity_bits')]
cb = re.sub(r'\n\s*set_output_multiple\([^;]*\);', '', cb)
cb = cb.rstrip()
assert cb.endswith('}')
fns = bc[bc.index('inline void ' + N + '::interleave_parity_bits'):bc.index(N + '::~' + N)]
tabs = bc[bc.index('const int ' + N + '::twist16n'):bc.index('} /* namespace dtv */')]
res = HDR + '''#include <cstdint>
#include <vector>
#include <cstring>
#include "gnuradio/dtv/dvb_config.h"
#include "gnuradio/dtv/dvbt2_config.h"
#include "dvb_defines.h"
namespace gr { namespace dtv {
struct T2BitIl {
''' + members.replace('inline void interleave_parity_bits', 'void interleave_parity_bits').replace('inline void\n    twist', 'void\n    twist') + '''
    T2BitIl(''' + params + ''');
};
T2BitIl::T2BitIl(''' + params + ''')
''' + cb + '''
''' + fns.replace('inline void', 'void') + tabs + '''
} }
'''
res = res.replace(N, 'T2BitIl')
open(os.path.join(out, 't2bitil_gen.h'), 'w').write(res)
print('t2bitil_gen.h', len(res))

# ---------------- DVB-T: continual pilot and TPS carrier positions (dvbt_reference_signals) ----------------
rs = rd('lib/dvbt/dvbt_reference_signals_impl.cc')
res = HDR
for nm, key in (('T1_CP_2K', 'd_cpilot_carriers_2k'), ('T1_TPS_2K', 'd_tps_carriers_2k'), ('T1_CP_8K', 'd_cpilot_carriers_8k'), ('T1_TPS_8K', 'd_tps_carriers_8k')):
    m = re.search(key + r'\[[^\]]*\]\s*=\s*\{([^}]*)\}', rs)
    vals = [int(v) for v in re.findall(r'\d+', m.group(1))]
    res += 'static const int %s[%d] = {%s};\n' % (nm, len(vals), ','.join(map(str, vals)))
open(os.path.join(out, 't1_gen.h'), 'w').write(res)
print('t1_gen.h', len(res))
